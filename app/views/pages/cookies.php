<h2 id="o-que-sao">O que são cookies e tecnologias semelhantes</h2>
<p>Cookies são pequenos arquivos gravados pelo navegador. Tecnologias semelhantes, como o <em>localStorage</em>, também guardam informações no seu dispositivo. Ambas podem ser essenciais ao funcionamento de um site ou servir para estatísticas e publicidade.</p>

<h2 id="quais-usamos">O que usamos</h2>
