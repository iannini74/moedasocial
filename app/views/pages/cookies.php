<p><strong>Medição sem cookies:</strong> mesmo sem consentimento, registramos estatísticas agregadas de navegação (página, origem, dispositivo, região aproximada) de forma pseudonimizada, sem cookies e sem guardar seu IP, com base no legítimo interesse. Saiba mais na <a href="/privacidade">Política de Privacidade</a>.</p>
<p><strong>Anúncios:</strong> os banners do patrocinador são sempre sinalizados como “Anúncio”, não usam cookies de terceiros e apenas registram, de forma agregada, visualizações e cliques.</p>

<h2 id="gerenciar">Como gerenciar</h2>
